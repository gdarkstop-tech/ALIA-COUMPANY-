import { createCipheriv, createDecipheriv, hkdfSync, randomBytes } from 'node:crypto';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import type { Env } from '../config/env';

/**
 * Private object storage for medical images (ADR 0015). Binaries never go into database rows; the
 * database keeps the key, hash and access rules. Every object is encrypted by the API before it is
 * written (AES-256-GCM, a fresh 96-bit IV per object, the object key bound as additional data so a
 * ciphertext cannot be moved to another key). Nothing in storage is ever public: objects are read
 * back only through the API, after an access check, behind short-lived signed links.
 *
 *   * LOCAL_ENCRYPTED — files on the API host's disk. Development and tests only: refused in
 *     production (ephemeral containers, several API instances, no managed backups).
 *   * A managed bucket (S3-compatible, in an approved region, with its own server-side encryption) is
 *     NOT_CONFIGURED: no adapter has been verified against a real bucket yet.
 */
export type ObjectStoreStatus = 'CONFIGURED' | 'DEV_ADAPTER' | 'NOT_CONFIGURED';

export interface ObjectStore {
  readonly status: ObjectStoreStatus;
  put(key: string, bytes: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  /** Idempotent: deleting a missing object succeeds. */
  delete(key: string): Promise<void>;
}

export class ObjectStoreUnavailable extends Error {
  constructor() {
    super('Object storage is not configured');
  }
}

const KEY_PATTERN = /^[a-z]{1,12}\/[0-9a-f-]{36}\.[a-z]{1,4}$/;
const MAGIC = Buffer.from('DMW1', 'latin1');

/** Object keys are generated by the API (`w/<uuid>.o`); anything else is refused before touching disk. */
export function assertObjectKey(key: string): void {
  if (!KEY_PATTERN.test(key)) throw new Error('Invalid object key');
}

export function encryptObject(masterKey: Buffer, key: string, plain: Buffer): Buffer {
  const iv = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', masterKey, iv);
  cipher.setAAD(Buffer.from(key, 'utf8'));
  const body = Buffer.concat([cipher.update(plain), cipher.final()]);
  return Buffer.concat([MAGIC, iv, cipher.getAuthTag(), body]);
}

export function decryptObject(masterKey: Buffer, key: string, sealed: Buffer): Buffer {
  if (sealed.length < 32 || !sealed.subarray(0, 4).equals(MAGIC)) throw new Error('Unrecognised object format');
  const decipher = createDecipheriv('aes-256-gcm', masterKey, sealed.subarray(4, 16));
  decipher.setAAD(Buffer.from(key, 'utf8'));
  decipher.setAuthTag(sealed.subarray(16, 32));
  return Buffer.concat([decipher.update(sealed.subarray(32)), decipher.final()]);
}

export class LocalEncryptedStore implements ObjectStore {
  readonly status = 'DEV_ADAPTER' as const;
  private readonly root: string;
  constructor(
    root: string,
    private readonly masterKey: Buffer,
  ) {
    if (masterKey.length !== 32) throw new Error('Object storage key must be 32 bytes');
    this.root = resolve(root);
  }
  private path(key: string) {
    assertObjectKey(key);
    return join(this.root, key);
  }
  async put(key: string, bytes: Buffer) {
    const file = this.path(key);
    await mkdir(dirname(file), { recursive: true, mode: 0o700 });
    // Written under a temporary name and renamed: a crash never leaves a half-written object.
    const tmp = `${file}.${randomBytes(6).toString('hex')}.tmp`;
    await writeFile(tmp, encryptObject(this.masterKey, key, bytes), { mode: 0o600 });
    await rename(tmp, file);
  }
  async get(key: string) {
    return decryptObject(this.masterKey, key, await readFile(this.path(key)));
  }
  async delete(key: string) {
    await rm(this.path(key), { force: true });
  }
}

export class UnconfiguredStore implements ObjectStore {
  readonly status = 'NOT_CONFIGURED' as const;
  async put(): Promise<void> {
    throw new ObjectStoreUnavailable();
  }
  async get(): Promise<Buffer> {
    throw new ObjectStoreUnavailable();
  }
  async delete(): Promise<void> {
    throw new ObjectStoreUnavailable();
  }
}

/**
 * The storage key comes from the secret manager (OBJECT_STORAGE_KEY, 32 bytes base64). Outside
 * production a development key is derived from the auth secret so local runs work out of the box;
 * it is labelled as such and never used in production.
 */
export function createObjectStore(env: Env): ObjectStore {
  if (env.NODE_ENV === 'production') return new UnconfiguredStore();
  const key = env.OBJECT_STORAGE_KEY
    ? Buffer.from(env.OBJECT_STORAGE_KEY, 'base64')
    : Buffer.from(hkdfSync('sha256', env.BETTER_AUTH_SECRET, 'dmw-object-storage', 'development-only object storage key', 32));
  return new LocalEncryptedStore(env.OBJECT_STORAGE_DIR, key);
}

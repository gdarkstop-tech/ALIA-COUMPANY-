import { createCipheriv, createDecipheriv, hkdfSync, randomBytes } from 'node:crypto';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client, S3ServiceException } from '@aws-sdk/client-s3';
import type { Env } from '../config/env';

/**
 * Private object storage for medical images (ADR 0015, ADR 0017). Binaries never go into database
 * rows; the database keeps the key, hash and access rules. Every object is encrypted by the API
 * before it is written (AES-256-GCM, a fresh 96-bit IV per object, the object key bound as
 * additional data so a ciphertext cannot be moved to another key). Nothing in storage is ever
 * public, and no storage URL is ever given to a client: objects are read back only through the
 * API, after an access check, behind short-lived signed links.
 *
 *   * LOCAL_ENCRYPTED (DEV_ADAPTER) — files on the API host's disk. Development and tests only:
 *     refused in production (ephemeral containers, several API instances, no managed backups).
 *   * S3_ENCRYPTED (CONFIGURED) — a private S3-compatible bucket over HTTPS, with server-side
 *     encryption (SSE-KMS by default) on top of the API's own encryption. In production it is
 *     switched on only when credentials, the encryption key AND an approval reference exist;
 *     otherwise storage is NOT_CONFIGURED and photo upload answers so.
 */
export type ObjectStoreStatus = 'CONFIGURED' | 'DEV_ADAPTER' | 'NOT_CONFIGURED';

export interface ObjectStore {
  readonly status: ObjectStoreStatus;
  /** Why storage is NOT_CONFIGURED (shown to administrators, never to patients). */
  readonly reason?: string;
  put(key: string, bytes: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  /** Idempotent: deleting a missing object succeeds. */
  delete(key: string): Promise<void>;
}

export class ObjectStoreUnavailable extends Error {
  constructor() {
    super('Object storage is not configured');
  }
}

/**
 * A storage operation failed (network, provider, missing object, integrity). Rendered as 503
 * STORAGE_UNAVAILABLE; the cause is logged, never sent to the client.
 */
export class ObjectStoreError extends Error {
  constructor(
    readonly kind: 'NOT_FOUND' | 'INTEGRITY' | 'PROVIDER',
    message: string,
    options?: { cause?: unknown },
  ) {
    super(message, options);
    this.name = 'ObjectStoreError';
  }
}

const KEY_PATTERN = /^[a-z]{1,12}\/[0-9a-f-]{36}\.[a-z]{1,4}$/;
const MAGIC = Buffer.from('DMW1', 'latin1');

/** Object keys are generated by the API (`w/<uuid>.o`); anything else is refused before touching storage. */
export function assertObjectKey(key: string): void {
  if (!KEY_PATTERN.test(key)) throw new Error('Invalid object key');
}

export function encryptObject(masterKey: Buffer, key: string, plain: Buffer): Buffer {
  const iv = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', masterKey, iv);
  cipher.setAAD(Buffer.from(key, 'utf8'));
  const body = Buffer.concat([cipher.update(plain), cipher.final()]);
  return Buffer.concat([MAGIC, iv, cipher.getAuthTag(), body]);
}

export function decryptObject(masterKey: Buffer, key: string, sealed: Buffer): Buffer {
  if (sealed.length < 32 || !sealed.subarray(0, 4).equals(MAGIC)) throw new Error('Unrecognised object format');
  const decipher = createDecipheriv('aes-256-gcm', masterKey, sealed.subarray(4, 16));
  decipher.setAAD(Buffer.from(key, 'utf8'));
  decipher.setAuthTag(sealed.subarray(16, 32));
  return Buffer.concat([decipher.update(sealed.subarray(32)), decipher.final()]);
}

function open(masterKey: Buffer, key: string, sealed: Buffer): Buffer {
  try {
    return decryptObject(masterKey, key, sealed);
  } catch (e) {
    throw new ObjectStoreError('INTEGRITY', 'Stored object failed its integrity check', { cause: e });
  }
}

export class LocalEncryptedStore implements ObjectStore {
  readonly status = 'DEV_ADAPTER' as const;
  private readonly root: string;
  constructor(
    root: string,
    private readonly masterKey: Buffer,
  ) {
    if (masterKey.length !== 32) throw new Error('Object storage key must be 32 bytes');
    this.root = resolve(root);
  }
  private path(key: string) {
    assertObjectKey(key);
    return join(this.root, key);
  }
  async put(key: string, bytes: Buffer) {
    const file = this.path(key);
    await mkdir(dirname(file), { recursive: true, mode: 0o700 });
    // Written under a temporary name and renamed: a crash never leaves a half-written object.
    const tmp = `${file}.${randomBytes(6).toString('hex')}.tmp`;
    await writeFile(tmp, encryptObject(this.masterKey, key, bytes), { mode: 0o600 });
    await rename(tmp, file);
  }
  async get(key: string) {
    let sealed: Buffer;
    try {
      sealed = await readFile(this.path(key));
    } catch (e) {
      throw new ObjectStoreError((e as NodeJS.ErrnoException).code === 'ENOENT' ? 'NOT_FOUND' : 'PROVIDER', 'Object could not be read', { cause: e });
    }
    return open(this.masterKey, key, sealed);
  }
  async delete(key: string) {
    await rm(this.path(key), { force: true });
  }
}

export type S3StoreConfig = {
  endpoint: string;
  region: string;
  bucket: string;
  accessKeyId: string;
  secretAccessKey: string;
  forcePathStyle: boolean;
  sse: 'aws:kms' | 'AES256' | 'provider-default';
  kmsKeyId?: string;
  requestTimeoutMs: number;
};

/**
 * Encrypted objects in a private S3-compatible bucket. Objects are written with server-side
 * encryption and `Cache-Control: no-store`, and are never addressed by a client: there are no
 * presigned or public URLs. The SDK retries transient failures (3 attempts) within the request
 * timeout; anything else becomes an ObjectStoreError.
 */
export class S3EncryptedStore implements ObjectStore {
  readonly status = 'CONFIGURED' as const;
  readonly client: S3Client;
  constructor(
    readonly config: S3StoreConfig,
    private readonly masterKey: Buffer,
    client?: S3Client,
  ) {
    if (masterKey.length !== 32) throw new Error('Object storage key must be 32 bytes');
    this.client =
      client ??
      new S3Client({
        endpoint: config.endpoint,
        region: config.region,
        forcePathStyle: config.forcePathStyle,
        credentials: { accessKeyId: config.accessKeyId, secretAccessKey: config.secretAccessKey },
        maxAttempts: 3,
        requestHandler: { requestTimeout: config.requestTimeoutMs, connectionTimeout: 5_000 },
      });
  }

  /** Server-side encryption parameters sent with every write. */
  get encryption() {
    if (this.config.sse === 'provider-default') return {};
    return { ServerSideEncryption: this.config.sse, ...(this.config.sse === 'aws:kms' && this.config.kmsKeyId ? { SSEKMSKeyId: this.config.kmsKeyId } : {}) } as const;
  }

  async put(key: string, bytes: Buffer) {
    assertObjectKey(key);
    try {
      await this.client.send(
        new PutObjectCommand({
          Bucket: this.config.bucket,
          Key: key,
          Body: encryptObject(this.masterKey, key, bytes),
          ContentType: 'application/octet-stream',
          CacheControl: 'no-store',
          Metadata: { format: 'dmw1' },
          ...this.encryption,
        }),
      );
    } catch (e) {
      throw new ObjectStoreError('PROVIDER', 'Object could not be stored', { cause: e });
    }
  }

  /** The stored (API-encrypted) bytes, without opening them — used by verification only. */
  async getSealed(key: string): Promise<Buffer> {
    assertObjectKey(key);
    try {
      const res = await this.client.send(new GetObjectCommand({ Bucket: this.config.bucket, Key: key }));
      return Buffer.from(await res.Body!.transformToByteArray());
    } catch (e) {
      const missing = e instanceof S3ServiceException && (e.name === 'NoSuchKey' || e.$metadata?.httpStatusCode === 404);
      throw new ObjectStoreError(missing ? 'NOT_FOUND' : 'PROVIDER', 'Object could not be read', { cause: e });
    }
  }

  async get(key: string) {
    return open(this.masterKey, key, await this.getSealed(key));
  }

  /**
   * Removes the current object. In a versioned bucket this leaves a delete marker; earlier
   * versions are erased by the lifecycle rule (≤ 30 days, the documented backup retention).
   */
  async delete(key: string) {
    assertObjectKey(key);
    try {
      await this.client.send(new DeleteObjectCommand({ Bucket: this.config.bucket, Key: key }));
    } catch (e) {
      throw new ObjectStoreError('PROVIDER', 'Object could not be deleted', { cause: e });
    }
  }
}

export class UnconfiguredStore implements ObjectStore {
  readonly status = 'NOT_CONFIGURED' as const;
  constructor(readonly reason = 'Photo storage is not configured') {}
  async put(): Promise<void> {
    throw new ObjectStoreUnavailable();
  }
  async get(): Promise<Buffer> {
    throw new ObjectStoreUnavailable();
  }
  async delete(): Promise<void> {
    throw new ObjectStoreUnavailable();
  }
}

/** The S3 settings from the environment, or the list of what is missing. */
export function s3Settings(env: Env): { config: S3StoreConfig; missing: [] } | { config: null; missing: string[] } {
  const missing = (
    [
      ['S3_ENDPOINT', env.S3_ENDPOINT],
      ['S3_REGION', env.S3_REGION],
      ['S3_BUCKET', env.S3_BUCKET],
      ['S3_ACCESS_KEY_ID', env.S3_ACCESS_KEY_ID],
      ['S3_SECRET_ACCESS_KEY', env.S3_SECRET_ACCESS_KEY],
    ] as const
  )
    .filter(([, v]) => !v)
    .map(([k]) => k);
  if (missing.length) return { config: null, missing };
  return {
    config: {
      endpoint: env.S3_ENDPOINT!,
      region: env.S3_REGION!,
      bucket: env.S3_BUCKET!,
      accessKeyId: env.S3_ACCESS_KEY_ID!,
      secretAccessKey: env.S3_SECRET_ACCESS_KEY!,
      forcePathStyle: env.S3_FORCE_PATH_STYLE,
      sse: env.S3_SSE,
      kmsKeyId: env.S3_KMS_KEY_ID,
      requestTimeoutMs: env.S3_REQUEST_TIMEOUT_MS,
    },
    missing: [],
  };
}

/**
 * The storage key comes from the secret manager (OBJECT_STORAGE_KEY, 32 bytes base64). Outside
 * production a development key is derived from the auth secret so local runs work out of the box;
 * it is labelled as such and never used in production.
 *
 * Production: the S3 adapter only with every setting present, an HTTPS endpoint (enforced at
 * start-up), a KMS key when SSE-KMS is chosen, and OBJECT_STORAGE_APPROVAL_REF; otherwise
 * NOT_CONFIGURED with the reason. Development / test: the S3 adapter when S3_* is set (e.g. a
 * local S3-compatible server), else the local encrypted directory.
 */
export function createObjectStore(env: Env): ObjectStore {
  const s3 = s3Settings(env);
  if (env.NODE_ENV === 'production') {
    if (!s3.config) return new UnconfiguredStore(`Missing ${s3.missing.join(', ')}`);
    if (!env.OBJECT_STORAGE_KEY) return new UnconfiguredStore('Missing OBJECT_STORAGE_KEY');
    if (s3.config.sse === 'aws:kms' && !s3.config.kmsKeyId) return new UnconfiguredStore('S3_SSE=aws:kms needs S3_KMS_KEY_ID');
    if (!env.OBJECT_STORAGE_APPROVAL_REF) return new UnconfiguredStore('Awaiting approval: OBJECT_STORAGE_APPROVAL_REF (contract, DPIA, cross-border authorisation)');
    return new S3EncryptedStore(s3.config, Buffer.from(env.OBJECT_STORAGE_KEY, 'base64'));
  }
  const key = env.OBJECT_STORAGE_KEY
    ? Buffer.from(env.OBJECT_STORAGE_KEY, 'base64')
    : Buffer.from(hkdfSync('sha256', env.BETTER_AUTH_SECRET, 'dmw-object-storage', 'development-only object storage key', 32));
  if (s3.config) return new S3EncryptedStore(s3.config, key);
  return new LocalEncryptedStore(env.OBJECT_STORAGE_DIR, key);
}
